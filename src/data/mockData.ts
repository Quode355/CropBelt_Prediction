// 农作物数据类型定义
export interface ProvinceCropData {
  省: string;
  面积: number;
  水稻类型1?: number;
  水稻类型2?: number;
  小麦面积?: number;
  玉米面积?: number;
  大豆面积?: number;
  棉花面积?: number;
}

export interface YearData {
  year: number;
  crops: {
    水稻: ProvinceCropData[];
    小麦?: ProvinceCropData[];
    玉米?: ProvinceCropData[];
    大豆?: ProvinceCropData[];
    棉花?: ProvinceCropData[];
  };
}

export interface CropData {
  年份: YearData[];
}

